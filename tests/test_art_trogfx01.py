"""TROG-FX-01 (docs/02-art/trog-fx-01-spec.md): the troglodytes' death parts, cut from the approved idle frame 0.

The grids, manifests and configs are generated by ``scripts/author_trogfx01.py``; these tests pin that the committed
files equal the generator, that the parts re-tile the approved sprite to the pixel, that nothing is drawn outside the
cells, the palette rules and the manifest contract the Rust presenter reads. The toolkit validators run with
``python3 -m scripts.pixelart validate assets/source/characters/troglodyte/death/<name>.pixelart.json`` (tested below)."""
from __future__ import annotations

import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import author_trogfx01 as fx  # noqa: E402

SPECIES = ("pygmy", "basher", "virtuoso")
TROG_KEYS = set("KdsmlHIcCweotTqgGuvV")
GORE_KEYS = {"R", "B", "P"}


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def pix(rows: list[str]) -> dict:
    return {(x, y): ch for y, row in enumerate(rows) for x, ch in enumerate(row) if ch != "."}


class TrogFx01Tests(unittest.TestCase):
    def test_committed_files_equal_the_generator(self):
        self.assertEqual(fx.main(["sheets", "--check"]), 0)
        for g, ase, *_ in fx.outputs():
            self.assertTrue(ase.is_file(), ase)

    def test_the_parts_re_tile_the_approved_idle_frame_exactly(self):
        for species in SPECIES:
            grid = load(fx.paths(species)["parts"][0])
            cell = grid["canvas"][0]
            man = load(fx.paths(species)["parts"][3])["death_parts"]
            src = pix(load(fx.CUTS[species]["grid"])["frames"][0]["cels"]["body"])
            seen: dict = {}
            for meta in man["parts"]:
                if meta["frame0_origin"] is None:
                    continue
                ox, oy = meta["frame0_origin"]
                body = pix(grid["frames"][meta["frame"]]["cels"]["body"])
                for (x, y), ch in body.items():
                    p = (x - cell // 2 + ox, y - cell // 2 + oy)
                    self.assertNotIn(p, seen, f"{species} {meta['id']} overlaps")
                    seen[p] = ch
            self.assertEqual(seen, src, f"{species}: the cuts are not the sprite")

    def test_every_cut_fits_its_cell_with_a_margin_and_no_pixel_is_isolated(self):
        for species in SPECIES:
            grid = load(fx.paths(species)["parts"][0])
            cell = grid["canvas"][0]
            self.assertEqual(grid["canvas"], [cell, cell])
            self.assertEqual(grid["pivot"], [cell // 2, cell // 2])
            for i, frame in enumerate(grid["frames"]):
                points = set()
                for layer in frame["cels"].values():
                    points |= set(pix(layer))
                self.assertTrue(points, f"{species} frame {i} is empty")
                xs, ys = [x for x, _ in points], [y for _, y in points]
                self.assertGreaterEqual(min(xs + ys), 1, f"{species} frame {i}")
                self.assertLessEqual(max(xs + ys), cell - 2, f"{species} frame {i}")

    def test_palettes_keep_to_the_family_keys_plus_three_blood_keys(self):
        for species in SPECIES:
            for kind in ("pose", "parts"):
                grid = load(fx.paths(species)[kind][0])
                keys = {p["key"] for p in grid["palette"]}
                self.assertLessEqual(len(keys), 20, f"{species} {kind}")
                self.assertTrue(keys <= TROG_KEYS | GORE_KEYS, f"{species} {kind}: {keys}")
                used = {ch for f in grid["frames"] for rows in f["cels"].values() for r in rows for ch in r} - {"."}
                self.assertEqual(used, keys, f"{species} {kind}: palette lists only keys the sheet uses")
                # The troglodyte keys keep the approved sprite's own colours.
                base = {p["key"]: p["rgba"] for p in load(fx.CUTS[species]["grid"])["palette"]}
                for p in grid["palette"]:
                    if p["key"] in base:
                        self.assertEqual(p["rgba"], base[p["key"]], f"{species} {p['key']}")

    def test_wounds_are_drawn_only_on_cut_faces_not_on_the_silhouette(self):
        for species in SPECIES:
            grid = load(fx.paths(species)["parts"][0])
            man = load(fx.paths(species)["parts"][3])["death_parts"]
            for meta in man["parts"]:
                gore = pix(grid["frames"][meta["frame"]]["cels"]["gore"])
                body = pix(grid["frames"][meta["frame"]]["cels"]["body"])
                if meta["class"] == "wound" and meta["frame0_origin"] is not None:
                    self.assertTrue(gore, f"{species} {meta['id']}: no wound")
                    self.assertFalse([p for p in gore if p not in body], f"{species} {meta['id']}")
                    self.assertTrue(all(ch in GORE_KEYS for ch in gore.values()))
                    self.assertNotIn("K", [body[p] for p in gore], f"{species} {meta['id']}")
                if meta["id"] == "bell":
                    self.assertFalse(gore, "the bell is clean brass")

    def test_the_manifest_contract_the_presenter_reads(self):
        parts_needed = {"head", "torso_upper", "torso_lower", "arm_near", "leg_near"}
        for species in SPECIES:
            man = load(fx.paths(species)["parts"][3])
            sec = man["death_parts"]
            ids = [p["id"] for p in sec["parts"]]
            self.assertEqual(ids, man["animation_tags"])
            self.assertTrue(parts_needed <= set(ids), species)
            self.assertTrue(set(fx.GENERIC) <= set(ids), species)
            self.assertEqual(sec["cell"], man["frame_size"])
            for i, p in enumerate(sec["parts"]):
                self.assertEqual(p["frame"], i)
                self.assertEqual(p["cell"], sec["cell"])
                if p["id"] in fx.GENERIC:
                    self.assertIsNone(p["frame0_origin"], p["id"])
                else:
                    self.assertEqual(set(p["presets"]) - {1, 2, 3, 4}, set())
            pose = load(fx.paths(species)["pose"][3])
            grid = load(fx.CUTS[species]["grid"])
            self.assertEqual(pose["frame_size"], grid["canvas"])
            self.assertEqual(pose["pivot"], grid["pivot"], "the pose pivot is the sprite's own")
            for m in (man, pose):
                self.assertEqual(m["review_status"], "prototype_fixture_unapproved")
                self.assertIn("ART-PUBLICATION-ALL-V1", m["license"])

    def test_only_the_virtuoso_has_a_bell_and_it_is_the_yellow_brass_of_its_sprite(self):
        for species in SPECIES:
            ids = [p["id"] for p in load(fx.paths(species)["parts"][3])["death_parts"]["parts"]]
            self.assertEqual("bell" in ids, species == "virtuoso", species)
        grid = load(fx.paths("virtuoso")["parts"][0])
        i = [t["name"] for t in grid["tags"]].index("bell")
        keys = {ch for ch in "".join(grid["frames"][i]["cels"]["body"]) if ch != "."}
        self.assertTrue({"t", "T"} <= keys, keys)

    def test_the_toolkit_validators_pass_on_every_config(self):
        for species in SPECIES:
            for kind in ("pose", "parts"):
                cfg = fx.paths(species)[kind][2]
                out = subprocess.run(
                    [sys.executable, "-m", "scripts.pixelart", "validate", str(cfg)],
                    cwd=ROOT, capture_output=True, text=True)
                self.assertEqual(out.returncode, 0, out.stdout + out.stderr)


if __name__ == "__main__":
    unittest.main()
